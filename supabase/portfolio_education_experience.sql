-- ============================
-- EDUCATION & EXPERIENCE TABLES
-- Run once in Supabase SQL Editor
-- ============================

CREATE TABLE public.portfolio_experience (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  organization text NOT NULL,
  start_date text NOT NULL,
  end_date text NOT NULL DEFAULT 'Now',
  description text,
  order_index int DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE public.portfolio_education (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  degree text NOT NULL,
  institution text NOT NULL,
  start_date text NOT NULL,
  end_date text NOT NULL DEFAULT 'Now',
  description text,
  order_index int DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE public.portfolio_experience ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.portfolio_education ENABLE ROW LEVEL SECURITY;

-- Public read
CREATE POLICY "public read experience"
ON public.portfolio_experience FOR SELECT USING (true);

CREATE POLICY "public read education"
ON public.portfolio_education FOR SELECT USING (true);

-- Admin full CRUD - Experience
CREATE POLICY "admin manage experience"
ON public.portfolio_experience FOR ALL
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  )
)
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  )
);

-- Admin full CRUD - Education
CREATE POLICY "admin manage education"
ON public.portfolio_education FOR ALL
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  )
)
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  )
);

